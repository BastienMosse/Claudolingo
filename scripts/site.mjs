// Syncs the landing page (docs/) with the extension's assets.
// The scene parts and crab lines are bundled into a plain script so the page also works
// when opened straight from disk (file:// blocks fetch).
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'fs';
import { join } from 'path';

const out = 'docs/assets';
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const parts = {};
for (const file of readdirSync('media/scene').filter(f => f.endsWith('.svg'))) {
  const raw = readFileSync(join('media/scene', file), 'utf-8');
  // Keep only what's inside the root <svg> (same as src/webview/scene.ts)
  parts[file.replace(/\.svg$/, '')] = raw.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
}
const messages = JSON.parse(readFileSync('media/messages.json', 'utf-8'));

writeFileSync(join(out, 'scene.js'),
  `// Generated by scripts/site.mjs from media/scene and media/messages.json. Do not edit.\n` +
  `window.CLAUDOLINGO = ${JSON.stringify({ parts, messages })};\n`);

cpSync('media/webview/scene.css', join(out, 'scene.css'));
cpSync('media/fonts/nunito.woff2', join(out, 'nunito.woff2'));

console.log(`docs/assets: ${Object.keys(parts).length} scene parts, ${Object.keys(messages).length} languages`);
